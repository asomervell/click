// Builds brand/ into public/ (served by Workers static assets, with no worker run) and writes
// src/brand-version.ts, the content hash used to version the stylesheet URL.
// Run: node scripts/build-brand.mjs (after python3 scripts/brand-images.py for generated PNGs).
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url));
const fonts = [
  ["IBM Plex Mono", 400, "IBMPlexMono-400-latin.woff2"],
  ["IBM Plex Mono", 500, "IBMPlexMono-500-latin.woff2"],
  ["Press Start 2P", 400, "PressStart2P-400-latin.woff2"],
];
const range = "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD";
const faces = fonts.map(([family, weight, file]) =>
  `@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};font-display:swap;src:url(/brand/fonts/${file}) format("woff2");unicode-range:${range}}`).join("\n");
// Self-hosted fonts replace the Google Fonts @import in tokens.css.
const tokens = read("brand/tokens.css").toString().replace(/@import url\([^)]*\);\s*/, "");
const css = [faces, tokens, read("brand/components.css").toString(), read("brand/site.css").toString()].join("\n");

const assets = {
  "/brand/click.css": { type: "text/css; charset=utf-8", data: Buffer.from(css) },
  "/brand/hero-campfire.png": { type: "image/png", data: read("brand/hero-campfire.png") },
  "/brand/lockup-magenta.png": { type: "image/png", data: read("brand/generated/lockup-magenta-208.png") },
  "/favicon.svg": { type: "image/svg+xml", data: read("brand/logos/favicon-16.svg") },
  "/favicon.ico": { type: "image/x-icon", data: read("brand/generated/favicon.ico") },
  "/apple-touch-icon.png": { type: "image/png", data: read("brand/generated/apple-touch-icon-192.png") },
  "/og.png": { type: "image/png", data: read("brand/generated/og.png") },
};
for (const [, , file] of fonts) assets[`/brand/fonts/${file}`] = { type: "font/woff2", data: read(`brand/fonts/${file}`) };
for (const file of readdirSync(new URL("../brand/logos", import.meta.url))) {
  if (file.endsWith(".svg")) assets[`/brand/logos/${file}`] = { type: "image/svg+xml", data: read(`brand/logos/${file}`) };
}

const hash = createHash("sha256");
for (const key of Object.keys(assets).sort()) hash.update(key).update(assets[key].data);
const version = hash.digest("hex").slice(0, 10);
const out = new URL("../public/", import.meta.url);
rmSync(out, { recursive: true, force: true });
for (const [path, asset] of Object.entries(assets)) {
  const file = new URL(`.${path}`, out);
  mkdirSync(dirname(file.pathname), { recursive: true });
  writeFileSync(file, asset.data);
}
// Static asset headers. /brand/click.css runs the worker first so a ?v= match can be marked immutable.
writeFileSync(new URL("_headers", out), `/*
  Cache-Control: public, max-age=86400
  X-Content-Type-Options: nosniff
  Access-Control-Allow-Origin: *

/favicon.ico
  Content-Type: image/x-icon
`);
writeFileSync(new URL("../src/brand-version.ts", import.meta.url), `// Generated by scripts/build-brand.mjs from brand/. Do not edit by hand.
export const BRAND_VERSION = ${JSON.stringify(version)};
`);
console.log(`public/: ${Object.keys(assets).length} assets, version ${version}`);
